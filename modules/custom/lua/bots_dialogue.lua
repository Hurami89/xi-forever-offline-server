local function hash(s)
    local h = 7
    for i = 1, #s do
        h = (h * 31 + s:byte(i)) % 2147483647
    end

    return h
end

function D.persona(bot)
    if not ensure() or not data.personas or #data.personas == 0 then
        return nil
    end

    local name = type(bot) == 'string' and bot or bot:getName()
    return data.personas[hash(name) % #data.personas + 1]
end

local function jobName(n)
    return JOB_NAMES[n or 0]
end

-- what is true about the bot right now (for the @conditions of the lines)
function D.condsFor(bot, extra)
    local c = {}
    local f = {}
    if env.facts then
        local ok, got = pcall(env.facts, bot)
        f = ok and type(got) == 'table' and got or {}
    end

    local doing = string.lower(f.doing or '')
    if doing:find('town') then
        c.town = true
    else
        c.field = true
    end

    if doing:find('hunt') or doing:find('party') or doing:find('battle') then
        c.hunt = true
    end

    if f.style == 'crafter' or f.style == 'gatherer' or f.style == 'merchant' or doing:find('synth') or doing:find('craft') or doing:find('gather') then
        c.craft = true
    end

    if MAGE[f.job or ''] then
        c.mage = true
    end

    if f.party then
        c.party = true
    end

    if f.gossip and f.gossip ~= '' then
        c.gossip = true
    end

    if (f.level or 99) < 30 then
        c.lowlevel = true
    end

    local hour = tonumber(os.date('%H')) or 12
    if hour >= 5 and hour < 11 then
        c.morning = true
    elseif hour >= 22 or hour < 4 then
        c.night = true
    end

    local kind = f.lsKind and string.lower(f.lsKind) or ''
    for _, k in ipairs({ 'endgame', 'exp', 'craft' }) do
        if kind:find(k) then
            c[k] = true
        end
    end

    local p = D.persona(bot)
    if p and p.leader then
        c.leader = true
    end

    if p and p.rival then
        c.rival = true
    end

    for k, v in pairs(extra or {}) do
        c[k] = v
    end

    return c, f
end

local function campFor(lvl)
    if not camps then
        return nil
    end

    local best
    for at, list in pairs(camps) do
        if at <= lvl and (not best or at > best) then
            best = at
        end
    end

    return best and pick(camps[best]) or nil
end

-- fill {slots}; nil when a slot has nothing true to put in it (the line is then not used)
local function fill(text, bot, f, ctx)
    local missing = false
    local out = text:gsub('{(%w+)}', function(key)
        local v
        if key == 'job' then
            v = f.job or jobName(bot:getMainJob())
        elseif key == 'lvl' then
            v = tostring(f.level or bot:getMainLvl())
        elseif key == 'sub' then
            local ok, s = pcall(function() return bot:getSubJob() end)
            v = ok and jobName(s) or nil
        elseif key == 'here' then
            v = f.zone
        elseif key == 'camp' then
            v = campFor(f.level or bot:getMainLvl())
        elseif key == 'member' then
            v = ctx.member
        elseif key == 'player' then
            v = ctx.player
        elseif key == 'doing' then
            v = f.doing
        end

        if not v or v == '' then
            missing = true
            return ''
        end

        return v
    end)

    if missing then
        return nil
    end

    out = out:gsub('[^\32-\126]', '')
    if #out > 115 then
        return nil
    end

    return out
end

local function voiced(text, bot)
    local p = D.persona(bot)
    if p and p.reg == 'terse' then
        text = text:gsub('%.$', '')
        text = text:sub(1, 1):lower() .. text:sub(2)
    end

    return text
end

local function textOf(l, bot)
    local p = D.persona(bot)
    if p and p.reg == 'polite' then
        return l.po or l.ca
    end

    return l.ca or l.po
end

local function mark(id, botName)
    local t = now()
    used[id] = t
    if botName then
        usedBy[botName .. '|' .. id] = t
    end

    dirty = true
end

-- one line for this bot and use (tag); nil when there is nothing fresh and true to say
function D.pick(bot, tag, ctx)
    if not ensure() or not bot then
        return nil
    end

    ctx = ctx or {}
    local list = byTag[tag]
    if not list then
        return nil
    end

    local conds, f = D.condsFor(bot, ctx.conds)
    local gap = GAPS[family(tag)]
    local t = now()
    local name = bot:getName()
    local fresh, all = {}, {}
    for _, l in ipairs(list) do
        local ok = true
        for c in pairs(l.conds) do
            if not conds[c] then
                ok = false
                break
            end
        end

        if ok then
            local text = fill(textOf(l, bot), bot, f, ctx)
            if text then
                local entry = { l = l, text = text, last = math.max(used[l.id] or 0, usedBy[name .. '|' .. l.id] or 0) }
                all[#all + 1] = entry
                if t - (used[l.id] or 0) >= gap[1] and t - (usedBy[name .. '|' .. l.id] or 0) >= gap[2] then
                    fresh[#fresh + 1] = entry
                end
            end
        end
    end

    local chosen = pick(fresh)
    if not chosen and gap[3] and #all > 0 then
        table.sort(all, function(a, b) return a.last < b.last end)
        chosen = all[rnd(1, math.min(3, #all))]
    end

    if not chosen then
        return nil
    end

    mark(chosen.l.id, name)
    return voiced(chosen.text, bot), chosen.l
end

-----------------------------------
-- sending (linkshell: bots wear their pearl as linkshell 2, so kinds 5 and 27 are both sent, as bots_ls.lua does)
-----------------------------------
local function send(botId, kind, text)
    if not BotChat or not (BotIsOnline and BotIsOnline(botId)) then
        return
    end

    if kind == 'ls' then
        BotChat(botId, 5, text)
        BotChat(botId, 27, text)
    elseif kind == 'party' then
        BotChat(botId, 4, text)
    elseif kind == 'say' then
        BotChat(botId, 0, text)
    end
end

local function typing(text)
    return math.max(2, math.floor(#text / 7))
end

-- queue a line; delay = seconds before it starts "typing"
function D.queue(bot, kind, text, delay)
    if not text or text == '' then
        return 0
    end

    local at = now() + (delay or 0) + typing(text)
    table.insert(queue, { at = at, botId = bot:getID(), kind = kind, text = text })
    return at
end

-- send right away (a bot about to log out)
function D.sendNow(bot, kind, text)
    if text and text ~= '' then
        send(bot:getID(), kind, text)
    end
end

-- once a second (bots_ls.lua tick)
function D.tick()
    local t = now()
    for i = #queue, 1, -1 do
        local q = queue[i]
        if t >= q.at then
            table.remove(queue, i)
            pcall(send, q.botId, q.kind, q.text)
        end
    end

    if dirty and t - savedAt >= SAVE_EVERY then
        pcall(saveState)
    end
end

function D.save()
    if dirty then
        pcall(saveState)
    end
end

-----------------------------------
-- scenes: a few members talk in turn
-----------------------------------
local function playScene(tag, members, ctx, kind, delay)
    local list = scenesByTag[tag]
    if not list or #members < 2 then
        return false
    end

    local t = now()
    local options = {}
    for _, s in ipairs(list) do
        if s.roles <= #members and t - (sceneAt[s.id] or 0) >= (s.cd or 60) * 60 then
            local conds = D.condsFor(members[1], ctx and ctx.conds)
            local ok = true
            for c in pairs(s.conds) do
                if not conds[c] then
                    ok = false
                    break
                end
            end

            if ok then
                options[#options + 1] = s
            end
        end
    end

    local s = pick(options)
    if not s then
        return false
    end

    -- roles go to different members, in a random order
    local pool = {}
    for _, m in ipairs(members) do
        pool[#pool + 1] = m
    end

    local cast = {}
    for r = 1, s.roles do
        cast[r] = table.remove(pool, rnd(1, #pool))
    end

    local at = delay or 0
    for _, line in ipairs(s.l) do
        local who = cast[line[1]]
        local p = D.persona(who)
        local text = (p and p.reg == 'polite') and line[3] or line[2]
        text = voiced(text, who)
        local done = D.queue(who, kind or 'ls', text, at)
        at = done - now() + rnd(3, 8)
    end

    sceneAt[s.id] = t
    dirty = true
    return true
end

D.playScene = playScene

