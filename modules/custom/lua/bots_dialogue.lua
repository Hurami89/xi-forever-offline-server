local function index()
    byTag, scenesByTag = {}, {}
    for _, l in ipairs(data.lines or {}) do
        local conds = {}
        for _, c in ipairs(l.c or {}) do
            conds[c] = true
        end

        l.conds = conds
        for _, t in ipairs(l.t or {}) do
            byTag[t] = byTag[t] or {}
            table.insert(byTag[t], l)
        end
    end

    for _, s in ipairs(data.scenes or {}) do
        local conds = {}
        for _, c in ipairs(s.c or {}) do
            conds[c] = true
        end

        s.conds = conds
        for _, t in ipairs(s.t or {}) do
            scenesByTag[t] = scenesByTag[t] or {}
            table.insert(scenesByTag[t], s)
        end
    end
end

local function loadState()
    local f = io.open(STATE_FILE, 'r')
    if not f then
        return
    end

    local t = now()
    for line in f:lines() do
        local kind, key, at = line:match('^(%a)\t([^\t]+)\t(%d+)$')
        at = tonumber(at)
        if kind and at and t - at < KEEP then
            if kind == 'l' then
                used[key] = at
            elseif kind == 'b' then
                usedBy[key] = at
            elseif kind == 's' then
                sceneAt[key] = at
            end
        end
    end

    f:close()
end

local function saveState()
    local t = now()
    local rows = {}
    for k, at in pairs(used) do
        if t - at < KEEP then
            rows[#rows + 1] = 'l\t' .. k .. '\t' .. at
        else
            used[k] = nil
        end
    end

    for k, at in pairs(usedBy) do
        if t - at < KEEP then
            rows[#rows + 1] = 'b\t' .. k .. '\t' .. at
        else
            usedBy[k] = nil
        end
    end

    for k, at in pairs(sceneAt) do
        if t - at < KEEP then
            rows[#rows + 1] = 's\t' .. k .. '\t' .. at
        end
    end

    local f = io.open(STATE_FILE .. '.tmp', 'w')
    if f then
        f:write(table.concat(rows, '\n') .. '\n')
        f:close()
        os.remove(STATE_FILE)
        os.rename(STATE_FILE .. '.tmp', STATE_FILE)
    end

    dirty, savedAt = false, t
end

local function ensure()
    if loaded then
        return data ~= nil
    end

    loaded = true
    local ok, d = pcall(require, DATA_PATH)
    if not ok or type(d) ~= 'table' or type(d.lines) ~= 'table' then
        print('[bots] written dialogue is off: bots_dialogue_data.lua could not be loaded: ' .. tostring(d))
        return false
    end

    data = d
    index()
    pcall(loadState)
    savedAt = now()
    local okC, c = pcall(require, 'modules/custom/lua/crowds_chat_data')
    camps = okC and type(c) == 'table' and c.camps or nil
    return true
end

function D.setup(e)
    env = e or {}
    ensure()
end

function D.available()
    return ensure()
end

local function aiOn()
    local ok, c = pcall(require, CONFIG)
    return ok and type(c) == 'table' and c.chat_ai == true
end

local function aiLines()
    local t = now()
    if t - aiAt >= 300 then
        aiAt = t
        aiPool = nil
        local chunk = loadfile(AI_PATH)
        if chunk then
            local ok, pool = pcall(chunk)
            if ok and type(pool) == 'table' and type(pool.ls) == 'table' and #pool.ls > 0 then
                aiPool = pool.ls
            end
        end
    end

    return aiPool
end

