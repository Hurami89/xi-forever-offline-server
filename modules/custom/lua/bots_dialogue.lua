-----------------------------------
-- XI: Forever Offline: written lines for the bot players. Used by bots_ls.lua, bots_chat.lua, bots.lua.
--
-- Linkshell chatter, hellos when you log in, welcomes when you join, reactions to what really happened (a level up,
-- a death, a cleared battlefield, a rank up), goodbyes, and the answers bots give when the AI is off or slow.
-- Everyone gets these, AI or not. With "AI chatter" on, some linkshell lines come from the AI pool instead
-- (crowds_chat_ai.lua, pool "ls"), written by your local model from these same lines as examples.
--
-- The lines: bots_dialogue_data.lua, GENERATED by C:\FFXISOLO\dialogue\build_dialogue.py from the dialogue packs
-- (the Vana'diel Living World pack) and our voice layer. Change the voice files there, not the data file.
--
-- Rules the lines keep:
--   - nothing is claimed that did not happen: event lines only follow the real event, {here} is the bot's real
--     area, {job}/{lvl}/{sub} its real job and level, {camp} a real camp for its level;
--   - each bot has one personality from the pack (always the same one, from its name): the polite ones type the pack's
--     own wording, the others a casual version, a few very short;
--   - repeats are spaced out: chatter and event lines not again for 24 hours (72 for the same bot), answers after
--     20 minutes; kept in bots_dialogue_state.txt so a restart does not reset it. With nothing fresh to say, a bot
--     says nothing (answers excepted: they reuse the line used longest ago).
-----------------------------------
local D = {}

local DATA_PATH  = 'modules/custom/lua/bots_dialogue_data'
local STATE_FILE = 'modules/custom/lua/bots_dialogue_state.txt'
local AI_PATH    = 'modules/custom/lua/crowds_chat_ai.lua'
local CONFIG     = 'modules/custom/lua/crowds_config'

-- seconds before a line may be used again: { by anyone, by the same bot, reuse the oldest when all are used }
local GAPS = {
    ambient = { 24 * 3600, 72 * 3600, false }, -- ls, say, party, pair, e.lfp ...
    event   = { 6 * 3600, 24 * 3600, true },   -- e.login, e.wb, e.levelup, e.death ...
    react   = { 600, 2 * 3600, true },         -- e.*_react
    reply   = { 1200, 6 * 3600, true },        -- r.*
}
local EVENT_GAP    = 90   -- seconds between two event reactions in one linkshell
local AI_LS_SHARE  = 0.4  -- with AI chatter on: share of linkshell chatter taken from the AI pool
local SCENE_SHARE  = 0.25 -- share of linkshell chatter that is a short scene between members
local SAVE_EVERY   = 300
local KEEP         = 72 * 3600

local JOB_NAMES = { 'WAR', 'MNK', 'WHM', 'BLM', 'RDM', 'THF', 'PLD', 'DRK', 'BST', 'BRD', 'RNG', 'SAM', 'NIN', 'DRG', 'SMN', 'BLU', 'COR', 'PUP' }
local MAGE = { WHM = true, BLM = true, RDM = true, SMN = true, BLU = true }

local data, byTag, scenesByTag
local env = {}             -- from bots.lua: facts(bot)
local used = {}            -- [line id] = time (anyone)
local usedBy = {}          -- [bot name .. '|' .. line id] = time
local sceneAt = {}         -- [scene id] = time
local eventAt = {}         -- [shell key] = time
local queue = {}           -- { at, botId, kind, text }
local loaded, dirty, savedAt = false, false, 0
local aiPool, aiAt = nil, 0
local camps

local function now()
    return os.time()
end

local function rnd(a, b)
    return math.random(a, b)
end

local function pick(list)
    if not list or #list == 0 then
        return nil
    end

    return list[rnd(1, #list)]
end

local function family(tag)
    if tag:sub(1, 2) == 'r.' then
        return 'reply'
    elseif tag:sub(-6) == '_react' then
        return 'react'
    elseif tag:sub(1, 2) == 'e.' and tag ~= 'e.lfp' and tag ~= 'e.lfm' then
        return 'event'
    end

    return 'ambient'
end

