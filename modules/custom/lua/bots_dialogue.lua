local function others(members, bot)
    local out = {}
    for _, m in ipairs(members or {}) do
        if m:getID() ~= bot:getID() then
            out[#out + 1] = m
        end
    end

    return out
end

-- what the bot is doing (bots.lua facts: bots_craft / bots_bcnm / bots_quests describe it) -> lines about it
function D.activityTag(bot)
    if not env.facts then
        return nil
    end

    local ok, f = pcall(env.facts, bot)
    local doing = ok and type(f) == 'table' and string.lower(f.doing or '') or ''
    if doing:find('^crafting') or doing:find('^gathering') then
        return 'e.craft'
    elseif doing:find('bcnm') or doing:find('ksnm') or doing:find('battlefield') then
        return 'e.bcnm_start'
    elseif doing:find('^quest') or doing:find('^mission') then
        return 'e.quest'
    end

    return nil
end

-- now and then in your shell: a scene, a line from the AI pool, or a written line. False: nothing to say.
function D.lsAmbient(members, player)
    if not ensure() or #members == 0 then
        return false
    end

    local quiet = #members <= 3
    local ctx = { player = player and player:getName(), conds = { busy = #members >= 5 or nil, quiet = quiet or nil } }
    if #members >= 2 and math.random() < SCENE_SHARE and playScene('ls', members, ctx, 'ls', rnd(0, 5)) then
        return true
    end

    local b = pick(members)
    if aiOn() and math.random() < AI_LS_SHARE then
        local pool = aiLines()
        local raw = pool and pick(pool)
        if raw then
            local f = {}
            if env.facts then
                local ok, got = pcall(env.facts, b)
                f = ok and type(got) == 'table' and got or {}
            end

            local text = fill(raw, b, f, ctx)
            if text then
                D.queue(b, 'ls', text, rnd(0, 5))
                return true
            end
        end
    end

    local other = others(members, b)
    ctx.member = #other > 0 and pick(other):getName() or nil

    -- half the time: about what it is really doing right now (crafting, a battlefield, a quest)
    local text
    if math.random() < 0.5 then
        local tag = D.activityTag(b)
        if tag then
            text = D.pick(b, tag, ctx)
        end
    end

    text = text or D.pick(b, 'ls', ctx)
    if text then
        D.queue(b, 'ls', text, rnd(0, 5))
        return true
    end

    return false
end

-- you logged in (gapDays: days since you were last on)
function D.onPlayerLogin(player, members, gapDays)
    if not ensure() or #members == 0 then
        return false
    end

    local tag = (gapDays or 0) >= 3 and 'e.wb_long' or 'e.wb'
    local ctx = { player = player:getName() }
    local delay = rnd(6, 15)
    if #members >= 2 and math.random() < 0.4 and playScene(tag, members, ctx, 'ls', delay) then
        return true
    end

    local pool = {}
    for _, m in ipairs(members) do
        pool[#pool + 1] = m
    end

    local said = false
    local count = math.min(#pool, math.random() < 0.5 and 2 or 1)
    for _ = 1, count do
        local b = table.remove(pool, rnd(1, #pool))
        local text = D.pick(b, tag, ctx) or (tag == 'e.wb_long' and D.pick(b, 'e.wb', ctx)) or nil
        if text then
            delay = D.queue(b, 'ls', text, delay) - now() + rnd(2, 6)
            said = true
        end
    end

    return said
end

-- you joined the shell
function D.onPlayerJoined(player, members)
    if not ensure() or #members == 0 then
        return false
    end

    local ctx = { player = player:getName() }
    if #members >= 2 and math.random() < 0.5 and playScene('e.join', members, ctx, 'ls', rnd(8, 15)) then
        return true
    end

    local b = pick(members)
    local text = D.pick(b, 'e.join', ctx)
    if text then
        D.queue(b, 'ls', text, rnd(8, 15))
        return true
    end

    return false
end

-- a member logged in / is about to log out, while you are on
function D.onBotLogin(bot, members, player)
    if not ensure() or math.random() > 0.35 then
        return false
    end

    local text = D.pick(bot, 'e.login', { player = player and player:getName(), conds = { busy = #members >= 5 or nil } })
    if text then
        D.queue(bot, 'ls', text, rnd(5, 20))
        return true
    end

    return false
end

function D.onBotLogout(bot, members, player)
    if not ensure() or math.random() > 0.35 then
        return false
    end

    local text = D.pick(bot, 'e.logout', { player = player and player:getName() })
    if text then
        D.sendNow(bot, 'ls', text)
        -- someone says bye back
        local other = others(members, bot)
        if #other > 0 and math.random() < 0.5 then
            local b = pick(other)
            local back = D.pick(b, 'r.bye', {})
            if back then
                D.queue(b, 'ls', back, rnd(1, 4))
            end
        end

        return true
    end

    return false
end

-- what a bot's diary entry (bots.lua) means here: { own line, others react, chance it mentions it at all }
local EVENTS = {
    { pat = '^hit level',            own = 'e.levelup',  react = 'e.levelup_react', chance = 0.5 },
    { pat = '^switched to',          own = 'e.jobchange', chance = 0.25 },
    { pat = '^got killed',           own = 'e.death',    react = 'e.death_react',   chance = 0.4 },
    { pat = '^bought some new gear', own = 'e.gear',     react = 'e.gear_react',    chance = 0.25 },
    { pat = '^cleared a',            own = 'e.win',      react = 'e.win_react',     chance = 0.6 },
    { pat = '^wiped in a',           own = 'e.wipe',     scene = 'e.wipe',          chance = 0.5 },
    { pat = '^made nation rank',     own = 'e.rankup',   react = 'e.rankup_react',  chance = 0.6 },
}

-- something really happened to a member of your shell (bots.lua diary)
function D.onBotEvent(bot, text, members, shellKey)
    if not ensure() or not text then
        return false
    end

    local ev
    for _, e in ipairs(EVENTS) do
        if text:find(e.pat) then
            ev = e
            break
        end
    end

    local t = now()
    if not ev or math.random() > ev.chance or t - (eventAt[shellKey or 'any'] or 0) < EVENT_GAP then
        return false
    end

    -- a level up only gets a line at round levels or now and then (no "ding" every level for 50 bots)
    if ev.own == 'e.levelup' then
        local lvl = tonumber(text:match('level (%d+)')) or 0
        if lvl % 5 ~= 0 and math.random() > 0.3 then
            return false
        end
    end

    local other = others(members, bot)
    if ev.scene and #members >= 2 and math.random() < 0.5 then
        local cast = { bot }
        for _, m in ipairs(other) do
            cast[#cast + 1] = m
        end

        if playScene(ev.scene, cast, {}, 'ls', rnd(4, 10)) then
            eventAt[shellKey or 'any'] = t
            return true
        end
    end

    local own = D.pick(bot, ev.own, {})
    if not own then
        return false
    end

    eventAt[shellKey or 'any'] = t
    local at = D.queue(bot, 'ls', own, rnd(3, 10))
    if ev.react and #other > 0 then
        local n = math.min(#other, math.random() < 0.4 and 2 or 1)
        local delay = at - now() + rnd(2, 5)
        for _ = 1, n do
            local b = table.remove(other, rnd(1, #other))
            local r = D.pick(b, ev.react, { member = bot:getName() })
            if r then
                delay = D.queue(b, 'ls', r, delay) - now() + rnd(1, 4)
            end
        end
    end

    return true
end

