-- answers without the AI (bots_chat.lua): what was said -> the kind of answer
-----------------------------------
local function has(s, ...)
    for _, w in ipairs({ ... }) do
        if s:find(w) then
            return true
        end
    end

    return false
end

function D.replyKind(text, facts)
    local s = ' ' .. string.lower(text or '') .. ' '
    if has(s, 'party', '%f[%a]pt%f[%A]', 'join', '%f[%a]inv') then
        return (facts and facts.busy) and 'r.no' or 'r.yes'
    elseif has(s, 'where are you', 'where r u', 'where u at', 'which zone', 'where you at') then
        return 'r.where'
    elseif has(s, 'what are you doing', 'what you doing', 'wyd', 'what are you up to', "what's up", 'whats up', 'sup%f[%A]') then
        return 'r.doing'
    elseif has(s, 'level', '%f[%a]lvl', 'what job', 'which job', 'your job') then
        return 'r.job'
    elseif has(s, 'thank', '%f[%a]ty%f[%A]', '%f[%a]thx', '%f[%a]tyvm') then
        return 'r.yw'
    elseif has(s, '%f[%a]gz', 'grats', 'congrat') then
        return 'r.thanks'
    elseif has(s, '%f[%a]bye', '%f[%a]cya', 'see ya', 'good night', '%f[%a]gn%f[%A]', 'gotta go', 'logging') then
        return 'r.bye'
    elseif has(s, '%f[%a]back%f[%A]', '%f[%a]re%f[%A]') and #s < 14 then
        return 'r.back'
    elseif has(s, '^ hi%f[%A]', '^ hiya', '^ hello', '^ hey', '^ heya', '^ yo ', 'o/', '\\o') then
        return 'r.greet'
    elseif has(s, 'new to', 'first time', 'how do i', 'where do i', 'what should i', 'any tips', 'advice') then
        return 'r.newbie'
    elseif has(s, 'help', 'can you', 'could you') then
        return 'r.help'
    elseif has(s, 'died', 'wiped', 'no drop', 'failed', 'ugh', 'sigh', '%f[%a]rip%f[%A]') then
        return 'r.sympathy'
    elseif has(s, 'ding', 'got it', 'finally', 'dropped', 'leveled') then
        return 'r.congrats'
    elseif has(s, '%f[%a]lol', 'haha', '%f[%a]lmao', '%f[%a]heh') then
        return 'r.laugh'
    elseif has(s, '%?') then
        return 'r.unsure'
    end

    return 'r.misc'
end

-- an answer to a player (tell, party, linkshell) when the AI has none; nil = nothing fitting
function D.reply(bot, text, facts, playerName)
    if not ensure() then
        return nil
    end

    local kind = D.replyKind(text, facts)
    local ctx = { player = playerName }
    return D.pick(bot, kind, ctx) or (kind ~= 'r.misc' and D.pick(bot, 'r.misc', ctx)) or nil
end

-- two lines two bots say to each other in town (crowds_chat.lua)
function D.pair()
    if not ensure() then
        return nil
    end

    local l = pick(byTag.pair)
    if l and l.an then
        return { l.ca, l.an }
    end

    return nil
end

-- a few example lines in a personality's voice (for tests and the in-game check)
function D.sample(tag, n)
    if not ensure() then
        return {}
    end

    local out = {}
    for _, l in ipairs(byTag[tag] or {}) do
        if #out >= (n or 5) then
            break
        end

        out[#out + 1] = l.ca
    end

    return out
end

function D.stats()
    if not ensure() then
        return 'written dialogue: not loaded'
    end

    return string.format('written dialogue: %d lines, %d scenes, %d personalities; %d lines used lately, %d waiting to be sent',
        #data.lines, #(data.scenes or {}), #(data.personas or {}), (function()
            local n = 0
            for _ in pairs(used) do
                n = n + 1
            end

            return n
        end)(), #queue)
end

-- for the tests
D._reset = function()
    used, usedBy, sceneAt, eventAt, queue = {}, {}, {}, {}, {}
end
D._queue = function()
    return queue
end

return D
