local ERA_CAPS =
{
    { maxLevel = 50,  cap = 200 },
    { maxLevel = 60,  cap = 250 },
    { maxLevel = 255, cap = 300 },
}

local configOk, config = pcall(require, 'modules/custom/lua/era_exp_config')
local enabled = not configOk or type(config) ~= 'table' or config.enabled ~= false

local applied = false

local function applyEraExperience()
    if applied then
        return true
    end

    if
        xi == nil or xi.data == nil or xi.data.experiencePoints == nil or
        type(xi.data.experiencePoints.baseTable) ~= 'table' or
        xi.experiencePoints == nil
    then
        return false
    end

    for difference, row in pairs(ERA_BASE) do
        xi.data.experiencePoints.baseTable[difference] = row
    end

    xi.experiencePoints.perMonsterCaps = ERA_CAPS

    -- hand the new table to the core, which keeps its own copy
    if type(ReloadExperienceData) == 'function' then
        ReloadExperienceData()
    end

    applied = true
    print('[era_exp] era experience tables are in use (per-monster caps 200 / 250 / 300)')
    return true
end

if not enabled then
    print('[era_exp] switched off in the launcher - the game\'s normal experience tables are in use')
elseif not applyEraExperience() then
    -- the tables were not loaded yet when this file ran: try again when the first player logs in
    m:addOverride('xi.player.onGameIn', function(player, firstLogin, zoning)
        super(player, firstLogin, zoning)

        if not applied and not applyEraExperience() then
            print('[era_exp] could not find the experience tables - the game\'s normal tables are in use')
        end
    end)
end

return m
